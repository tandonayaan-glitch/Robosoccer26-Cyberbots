#!/usr/bin/env python3
"""Provision the Bluetooth credentials of the VVS Cyberbots robot - ONE command.

  python3 tools/provision.py --mega-port COM3        # Windows;  /dev/ttyACM0 on Linux, /dev/cu.usbmodem* on macOS

What it does
  1. makes a random 32-byte shared key and a random console passcode (Python 'secrets', i.e. the operating system's CSPRNG)
  2. writes them to remote_esp32/secrets.h (git-ignored, file mode 600)           -> you then flash the ESP32 sketch
  3. with --mega-port: sends   :authkey <key>   to the Mega over USB and checks the key fingerprint it reports -> no Mega reflash needed

Secrets are never committed (secrets.h is in .gitignore) and the key is never printed unless you ask (--print-mega-command).
The USB cable to the Mega is trusted: whoever can plug into it can set a key. Anyone who knows the passcode can unlock the remote from any laptop.

Other uses
  --reuse            keep the key/passcode already in secrets.h and only (re)send the key to the Mega (e.g. after replacing the Mega)
  --new-passcode     keep the key, make a new passcode (e.g. a team member left). Reflash the ESP32 afterwards.
  --no-passcode      write CONSOLE_REQUIRE_PASSCODE 0  (esp32connect alone connects; less secure, see docs/BLUETOOTH.md)
  --passcode TEXT    choose the passcode yourself (>= 8 characters)
  --clear            erase the key in the Mega (the remote can then no longer control the robot)
  --out FILE         write somewhere else (default remote_esp32/secrets.h)
  --selftest         check the fingerprint code against the firmware's test vector
"""
import argparse, hashlib, hmac, os, re, secrets, sys, time

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DEFAULT_OUT = os.path.join(ROOT, "remote_esp32", "secrets.h")
ALPHABET = "ABCDEFGHJKLMNPQRSTUVWXYZ23456789"          # no 0/O/1/I confusion


def fingerprint(key_hex: str) -> str:
    """First 4 bytes of HMAC-SHA256(key, "FPR") - the same value the Mega and the ESP32 print."""
    return hmac.new(bytes.fromhex(key_hex), b"FPR", hashlib.sha256).hexdigest()[:8]


def new_passcode() -> str:
    g = ["".join(secrets.choice(ALPHABET) for _ in range(4)) for _ in range(3)]
    return "-".join(g)


def valid_key(k: str) -> bool:
    return bool(re.fullmatch(r"[0-9a-fA-F]{64}", k)) and len(set(bytes.fromhex(k))) > 1


def read_existing(path):
    if not os.path.exists(path):
        return None, None, None
    txt = open(path, encoding="utf-8").read()
    key = re.search(r'#define\s+SHARED_KEY_HEX\s+"([^"]*)"', txt)
    pw = re.search(r'#define\s+CONSOLE_PASSCODE\s+"([^"]*)"', txt)
    req = re.search(r'#define\s+CONSOLE_REQUIRE_PASSCODE\s+(\d)', txt)
    return (key.group(1) if key else None), (pw.group(1) if pw else None), (int(req.group(1)) if req else 1)


def write_secrets(path, key, passcode, require):
    body = f'''// secrets.h - GENERATED by tools/provision.py. NEVER COMMIT THIS FILE (it is in .gitignore).
// Regenerate with:  python3 tools/provision.py --force      Re-send the key to a Mega with:  python3 tools/provision.py --reuse --mega-port <port>
#define SHARED_KEY_HEX   "{key}"
#define CONSOLE_PASSCODE "{passcode}"
#define CONSOLE_REQUIRE_PASSCODE {1 if require else 0}
#define CONSOLE_IDLE_LOCK_MS 0UL     // 0 = stay connected until esp32disconnect; e.g. 300000UL = also lock after 5 idle minutes
'''
    fd = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
    with os.fdopen(fd, "w", encoding="utf-8") as f:
        f.write(body)
    try:
        os.chmod(path, 0o600)
    except OSError:
        pass


def mega_command(port, line, wait_boot, expect):
    try:
        import serial  # pyserial
    except ImportError:
        sys.exit("pyserial is needed to talk to the Mega:  python3 -m pip install pyserial   (or enter the command by hand, see --print-mega-command)")
    ser = serial.Serial(port, 115200, timeout=0.5)
    print(f"opened {port}; the Mega resets when the port opens - waiting {wait_boot:.0f} s for it to finish booting")
    time.sleep(wait_boot)
    ser.reset_input_buffer()
    ser.write(b"s\n")                      # 'stop': cancels the automatic attack start if the board just rebooted
    time.sleep(0.4)
    ser.write((line + "\n").encode())
    end = time.time() + 3.0
    out = ""
    while time.time() < end:
        out += ser.read(256).decode("utf-8", "replace")
        if expect in out:
            break
    ser.close()
    return out


def main():
    ap = argparse.ArgumentParser(description="Provision the VVS Cyberbots Bluetooth credentials (see the module docstring).")
    ap.add_argument("--mega-port"); ap.add_argument("--out", default=DEFAULT_OUT)
    ap.add_argument("--force", action="store_true", help="overwrite an existing secrets.h with NEW values")
    ap.add_argument("--reuse", action="store_true"); ap.add_argument("--new-passcode", action="store_true")
    ap.add_argument("--no-passcode", action="store_true"); ap.add_argument("--passcode")
    ap.add_argument("--clear", action="store_true"); ap.add_argument("--print-mega-command", action="store_true")
    ap.add_argument("--boot-wait", type=float, default=12.0, help="seconds to wait after opening the port (the Mega reboots and calibrates the gyro)")
    ap.add_argument("--selftest", action="store_true")
    a = ap.parse_args()

    if a.selftest:
        k = "000102030405060708090a0b0c0d0e0f101112131415161718191a1b1c1d1e1f"
        assert fingerprint(k) == "17a56f78", fingerprint(k)
        assert valid_key(k) and not valid_key("00" * 32) and not valid_key("12")
        print("selftest OK (fingerprint matches the firmware test vector)")
        return

    if a.clear:
        if not a.mega_port:
            sys.exit("--clear needs --mega-port")
        out = mega_command(a.mega_port, ":authkey clear", a.boot_wait, "ERASED")
        print("Mega key erased." if "ERASED" in out else "No confirmation seen. Output was:\n" + out)
        return

    key, pw, req = read_existing(a.out)
    have = key is not None and valid_key(key or "")
    if a.reuse:
        if not have:
            sys.exit(f"--reuse: no valid key in {a.out}")
    else:
        if have and not a.new_passcode and not a.force:
            sys.exit(f"{a.out} already exists with a key. Use --reuse (send it to a Mega), --new-passcode, or --force (replace everything).")
        if not a.new_passcode or not have:
            key = secrets.token_hex(32)
    if a.new_passcode or not (pw and not a.reuse and have) or a.passcode:
        pw = a.passcode or new_passcode()
    if a.passcode and len(a.passcode) < 8:
        sys.exit("the passcode must have at least 8 characters")
    require = 0 if a.no_passcode else (1 if req is None else req) if (a.reuse or a.new_passcode) else (0 if a.no_passcode else 1)
    if a.no_passcode:
        require = 0

    if not a.reuse:
        write_secrets(a.out, key, pw, require)
        print(f"wrote {a.out} (mode 600, not tracked by Git)")
        print(f"  console passcode : {pw}      <- type  esp32connect {pw}  in the ESP32's Serial Monitor. Shown once; it is also in secrets.h.")
        print(f"  key fingerprint  : {fingerprint(key)}   (the ESP32 and the Mega print the same value)")
        if not require:
            print("  WARNING: CONSOLE_REQUIRE_PASSCODE is 0: 'esp32connect' alone will connect.")
    else:
        print(f"using the key in {a.out}, fingerprint {fingerprint(key)}")

    cmd = f":authkey {key}"
    if a.print_mega_command:
        print("command for the Mega's USB Serial Monitor (line ending Newline):\n  " + cmd)
    if a.mega_port:
        print("SAFETY: lift the wheels or disconnect the motor battery - the Mega reboots and may start its automatic attack.")
        out = mega_command(a.mega_port, cmd, a.boot_wait, "fingerprint")
        m = re.search(r"fingerprint ([0-9a-f]{8})", out)
        if m and m.group(1) == fingerprint(key):
            print(f"Mega accepted the key; its fingerprint {m.group(1)} matches. Nothing to reflash on the Mega.")
        else:
            print("The Mega did not confirm the key. Output was:\n" + out)
            sys.exit(1)
    else:
        print("Next: either rerun with --mega-port <port>, or enter the key on the Mega yourself (--print-mega-command shows the line).")
    print("Then flash remote_esp32/remote_esp32.ino to the ESP32 (secrets.h is picked up from the same folder).")


if __name__ == "__main__":
    main()
